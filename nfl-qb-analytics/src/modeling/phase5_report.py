          f'* **Pre-draft:** college features improve on the historical median for some statistics. Intervals that '
          f'exclude zero for the structured model: {", ".join(LAB[t] for t in pre_sig) or "none"}. The gains are modest; '
          'college data alone cannot separate future starters from career backups very well.',
          '* **Post-draft:** knowing the actual pick helps much more (next section).',
          f'* **Structured vs direct:** the structured simulation is the best non-baseline model for {n_struct_best["pre_draft"]} of 10 '
