def examples() -> dict:
    from src.modeling.historical_backtest import historical_backtest
    from src.modeling.prediction_api import forecast_prospect, summarize, validate
    cases = [('Fernando Mendoza 2026, pre-draft', dict(name='Fernando Mendoza', draft_year=2026, mode='pre_draft')),
             ('Fernando Mendoza 2026, post-draft', dict(name='Fernando Mendoza', draft_year=2026, mode='post_draft')),
             ('Jaxson Dart 2025, post-draft', dict(name='Jaxson Dart', draft_year=2025, mode='post_draft')),
             ('Seth Henigan (final season 2024, undrafted), pre-draft', dict(cfbd_player_id='4606194', final_season=2024, mode='pre_draft')),
             ('Seth Henigan, post-draft (no pick)', dict(cfbd_player_id='4606194', final_season=2024, mode='post_draft')),
             ('Fernando Mendoza, hypothetical pick 40', dict(name='Fernando Mendoza', draft_year=2026, mode='post_draft', assumed_pick=40))]
    out = {}
    for label, kw in cases:
        t = time.time()
        f = forecast_prospect(**kw)
        out[label] = {'kwargs': kw, 'seconds': round(time.time() - t, 2), 'valid': validate(f) == [], 'summary': summarize(f),
                      'statuses': {k: f[k].get('status') for k in ('draft', 'career', 'comparisons')} if f.get('status') == 'available' else {},
                      'forecast': f}
    bts = {}
    for name, yr in (('Josh Allen', 2018), ('Matt Ryan', 2008), ('C.J. Stroud', 2023)):
        b = historical_backtest(name, yr)
        bts[f'{name} {yr}'] = b
    (R / 'phase5_5_examples.json').write_text(json.dumps({'forecasts': out, 'backtests': bts}, indent=2, default=str), encoding='utf-8')
    return {'forecasts': out, 'backtests': bts}


