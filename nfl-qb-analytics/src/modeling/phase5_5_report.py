def coverage_summary(IM: pd.DataFrame) -> pd.DataFrame:
    g = IM.groupby(['feature_set', 'method'])[['coverage50', 'coverage80', 'coverage90']].agg(['mean', 'min', 'max'])
    g.columns = [f'{a}_{b}' for a, b in g.columns]
    return g.reset_index()


