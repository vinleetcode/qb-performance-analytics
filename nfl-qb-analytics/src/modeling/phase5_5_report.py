def reliability_report() -> str:
    PM, PMp = csv('v11_point_metrics'), csv('v11_point_metrics', PT)
    ST = pd.read_parquet(R / 'v11_struct_backtest.parquet')
    sel = pd.read_csv(R / 'v11_selection.csv')
    meta = A.load_metadata(V11.MODEL_DIR)
    rnd, cls = csv('v11_errors_by_round'), csv('v11_errors_by_class')
    act, prd, coh = csv('v11_errors_by_actual_opportunity'), csv('v11_errors_by_predicted_opportunity'), csv('v11_point_coherence')
    st_mae = (ST.assign(e=lambda x: (x['pred_mean'] - x['y']).abs()).groupby(['feature_set', 'target'])['e'].mean().rename('structured'))
    w = PM.pivot_table(index=['feature_set', 'target'], columns='model', values='mae')
    w['per_target_rule'] = PMp[PMp['model'] == 'selected'].set_index(['feature_set', 'target'])['mae']
    w = w.join(st_mae)
    cols = ['median', 'mean'] + [c for c in ('round_mean',) if c in w] + ['ridge', 'poisson', 'hurdle', 'per_target_rule', 'selected', 'structured']
    W = w[cols].reset_index()
    rm = PM[PM['model'] == 'selected'][['feature_set', 'target', 'mae', 'rmse', 'bias', 'mae_skill_vs_median']]
    final = {fs: next(iter(meta['selection'][fs].values()))['point'] for fs in meta['selection']}
    chosen = {fs: sel[sel['feature_set'] == fs].groupby('test_year')['point'].first() for fs in ('pre_draft', 'post_draft')}
    skill = PM[PM['model'] == 'selected'].groupby('feature_set')['mae_skill_vs_median'].mean()
    skill_pt = PMp[PMp['model'] == 'selected'].groupby('feature_set')['mae_skill_vs_median'].mean()
    fixed_best = {fs: PM[(PM['feature_set'] == fs) & PM['model'].isin(['ridge', 'poisson', 'hurdle'])].groupby('model')['mae_skill_vs_median'].mean()
                  for fs in ('pre_draft', 'post_draft')}
    rb = rnd[(rnd['model'] == 'selected') & rnd['target'].isin(['games_started', 'pass_yards'])]
    ab = act[(act['model'] == 'selected') & act['target'].isin(['games_started', 'pass_yards'])]
    pb = prd[(prd['model'] == 'selected') & prd['target'].isin(['games_started', 'pass_yards'])]
    cb = cls[(cls['model'] == 'selected') & (cls['target'] == 'games_started')].pivot_table(index='test_year', columns='feature_set', values='bias').reset_index()
    cl = pd.read_csv(R5 / 'production_cluster.csv') if (R5 / 'production_cluster.csv').exists() else None
    ci_note = ''
    if cl is not None:
        a = cl[(cl['model'] == 'poisson') & (cl['baseline'] == 'median') & (cl['feature_set'] == 'pre_draft')]
        b = cl[(cl['model'] == 'ridge') & (cl['baseline'] == 'median') & (cl['feature_set'] == 'post_draft')]
        ci_note = (f' Phase 5\'s class-bootstrap intervals say the same: quasi-Poisson vs the median pre-draft excludes zero '
                   f'for {int((a["hi"] < 0).sum())} of 10 statistics; ridge vs the median post-draft excludes zero for '
                   f'{int((b["hi"] < 0).sum())} of 10.')
    n_struct_better = {fs: int((W[W['feature_set'] == fs]['structured'] < W[W['feature_set'] == fs]['selected']).sum()) for fs in ('pre_draft', 'post_draft')}
    best_fixed = {fs: fixed_best[fs].idxmax() for fs in fixed_best}
    n_struct_vs_fixed = {fs: int((W[W['feature_set'] == fs]['structured'] < W[W['feature_set'] == fs][best_fixed[fs]]).sum()) for fs in ('pre_draft', 'post_draft')}
    med_pre = int((chosen['pre_draft'] == 'median').sum())
    late_med = int((chosen['pre_draft'][chosen['pre_draft'].index >= 2017] == 'median').sum())
    rb_gs = rnd[(rnd['model'] == 'selected') & (rnd['target'] == 'games_started')].set_index(['feature_set', 'round_group'])['bias']
    pb_gs = prd[(prd['model'] == 'selected') & (prd['target'] == 'games_started')].set_index(['feature_set', 'predicted_opportunity'])['bias']
    ab_gs = act[(act['model'] == 'selected') & (act['target'] == 'games_started')].set_index(['feature_set', 'actual_opportunity'])['bias']
    L = ['# Model reliability (Phase 5.5)', '',
         'Generated by `python -m src.modeling.phase5_5_report`. Five-season NFL production of drafted QBs, nested '
         'chronological backtest: outer test classes 2012-2021 (107 QBs), five-season label embargo, every model choice '
         'made inside the development folds.', '',
         '## Summary', '',
         f'* **Post-draft forecasts clearly beat the baselines; pre-draft totals barely do.** Under nested '
         f'selection, average MAE skill vs the median is {skill["pre_draft"]:+.1%} pre-draft and {skill["post_draft"]:+.1%} '
         f'post-draft. Using one family for every fold does better ({best_fixed["pre_draft"]} {fixed_best["pre_draft"].max():+.1%} '
         f'pre-draft, {best_fixed["post_draft"]} {fixed_best["post_draft"].max():+.1%} post-draft), but picking that family '
         'used the test classes. Phase 5 reported those hindsight numbers.' + ci_note,
         f'* **The automated choice is unstable pre-draft.** The inner rule picked the historical median in {med_pre} of 10 '
         f'pre-draft folds, including {late_med} of the 5 folds from 2017 on. With about 10 QBs per validation class, the '
         'inner data cannot reliably tell the quasi-Poisson model from the median. Post-draft, the rule moved from the '
         'mean-by-round baseline (early folds) to ridge and quasi-Poisson as history accumulated. With all 183 QBs the '
         f'final rule picks `{final["pre_draft"]}` pre-draft and `{final["post_draft"]}` post-draft, and v1.1.0 ships those.',
         f'* **Direct models stay the default.** The structured simulation\'s mean beats the nested selection procedure for '
         f'{n_struct_better["pre_draft"]} of 10 statistics pre-draft and {n_struct_better["post_draft"]} post-draft, because the '
         'procedure often fell back to a baseline. Against the families v1.1.0 actually ships, it is better for only '
         f'{n_struct_vs_fixed["pre_draft"]} (pre-draft, vs {best_fixed["pre_draft"]}) and {n_struct_vs_fixed["post_draft"]} '
         f'(post-draft, vs {best_fixed["post_draft"]}). No alternative demonstrably beats the direct models, so they stay the '
         'default and the simulation supplies year-by-year shapes only.',
         f'* **First rule rejected.** Choosing separately per statistic from three inner classes gave average skill '
         f'{skill_pt["pre_draft"]:+.1%} pre-draft and {skill_pt["post_draft"]:+.1%} post-draft. v1.1.0 makes one choice of family '
         'and one of interval method per feature set, pooled across the ten statistics. That rule was designed after seeing '
         'the first result, which is disclosed.',
         f'* **Systematic errors.** Pre-draft forecasts under-predict first-round QBs badly (games started bias '
         f'{rb_gs.get(("pre_draft", "Round 1"), np.nan):+.1f}) and over-predict rounds 4-7 ({rb_gs.get(("pre_draft", "Rounds 4-7"), np.nan):+.1f}). '
         f'Adding the pick shrinks the first-round bias to {rb_gs.get(("post_draft", "Round 1"), np.nan):+.1f}. Grouped by the '
         f'*actual* outcome, the best careers are under-predicted (post-draft {ab_gs.get(("post_draft", "1000+ att"), np.nan):+.1f} '
         'starts for QBs with 1,000+ attempts). That is regression to the mean, unavoidable for an honest forecast. Grouped '
         f'by the *forecast* (the fair check), post-draft biases are small ({", ".join(f"{pb_gs.get(("post_draft", k), np.nan):+.1f}" for k in ("low", "mid", "high"))} '
         'for low/mid/high forecasts). Pre-draft forecasts sit low in every group '
         f'({", ".join(f"{pb_gs.get(("pre_draft", k), np.nan):+.1f}" for k in ("low", "mid", "high"))}): median-type forecasts sit '
         'below the mean of a right-skewed outcome.', '',
         '## Point accuracy (MAE) by statistic', '',
         md_table(W, '.1f'), '',
         '`selected` = v1.1.0 rule in the nested backtest; `per_target_rule` = the rejected first rule; `ridge` / `poisson` / '
         '`hurdle` = each family used for every fold (hindsight comparison); `structured` = simulation mean.', '',
         'Family chosen per outer fold: ' + '; '.join(f'{FS_LABEL[fs]}: ' + ', '.join(f'{y} {v}' for y, v in c.items()) for fs, c in chosen.items()) + '.', '',
         '## Selected model: MAE, RMSE, bias, skill vs the historical median', '', md_table(rm, '.3f'), '',
         '## Errors by draft round (selected model)', '', md_table(rb, '.1f'), '',
         '## Bias by draft class, games started', '', md_table(cb, '.1f'), '',
         'Bias drifts by class. Some classes produced more long-term starters than any college profile anticipated.', '',
         '## Low- vs high-opportunity QBs', '',
         'Grouped by the **actual** five-season pass attempts (shows regression to the mean by construction):', '',
         md_table(ab, '.1f'), '',
         'Grouped by the **predicted** attempts (thirds of the forecast; the fair calibration check):', '', md_table(pb, '.1f'), '',
         'Reading: when QBs are grouped by what they actually did, any forecast that is shrunk toward the mean '
         'under-predicts the top group and over-predicts the bottom group. That is unavoidable for an honest forecast with '
         'limited signal. The test that matters is the second table: QBs with high *forecasts* should, on average, '
         'reach them. Remaining bias there is genuine miscalibration of the point forecast.', '',
         '## Internal consistency of the point forecasts', '',
         'Independent models per statistic can contradict each other. Violations in the backtest, before and after the '
         'v1.1.0 projection (games started <= games played <= 85; completions, TDs and INTs <= attempts; rushing TDs <= '
         'rushes):', '', md_table(coh), '',
         read_section('similarity_audit_section.md'), '',
         read_section('trajectory_audit_section.md'), '']
    return '\n'.join(L)


